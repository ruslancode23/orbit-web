/**
 * Сервер требует не меньше стольких символов. Регистрация, смена пароля и
 * восстановление говорят об этом до отправки, а не показывают 400 после неё.
 */
export const MIN_PASSWORD_LENGTH = 10

/** Единственная формулировка правила о коротком пароле: все формы говорят её одинаково. */
export const SHORT_PASSWORD_MESSAGE = `Пароль должен быть не короче ${String(MIN_PASSWORD_LENGTH)} символов.`
