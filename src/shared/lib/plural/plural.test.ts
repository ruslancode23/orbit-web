import { pluralRu } from './plural'

const forms = ['реакция', 'реакции', 'реакций'] as const

it.each([
  [1, 'реакция'],
  [2, 'реакции'],
  [4, 'реакции'],
  [5, 'реакций'],
  [11, 'реакций'],
  [12, 'реакций'],
  [21, 'реакция'],
  [22, 'реакции'],
  [111, 'реакций'],
  [0, 'реакций'],
])('%i → %s', (count, word) => {
  expect(pluralRu(count, forms)).toBe(word)
})
